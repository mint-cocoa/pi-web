// Build the fixed, reviewed Python helper into the server bundle for SSH deployment.
// eslint-disable-next-line @typescript-eslint/no-require-imports
const fs = require("node:fs");
// eslint-disable-next-line @typescript-eslint/no-require-imports
const path = require("node:path");
const directory = path.join(__dirname, "../lib/runtime");
const source = fs.readFileSync(path.join(directory, "gateway.py"), "utf8").replace(/\r\n/g, "\n");
fs.writeFileSync(path.join(directory, "gateway-source.ts"), `// Generated by bin/build-runtime.js from gateway.py.\nexport const GATEWAY_SOURCE = ${JSON.stringify(Buffer.from(source).toString("base64"))};\n`);
